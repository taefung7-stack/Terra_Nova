for (const L of Object.keys(KO)) {
  const { SOURCE } = await import(`./_SOURCE-${L}.js`);
  if (SOURCE.length !== KO[L].length) throw new Error(`${L}: 챕터 수 ${SOURCE.length} ≠ 해석 ${KO[L].length}`);
  SOURCE.forEach((ch, i) => {
    const ko = KO[L][i];
    if (ko.length !== ch.sentences.length) throw new Error(`${L} Ch${ch.no}: 해석 ${ko.length} ≠ 원문 ${ch.sentences.length}`);
    // 화자 표시가 있는 문장은 해석에도 화자가 있어야 한다(대화문 짝 맞춤 검사)
    ch.sentences.forEach((en, j) => {
      const sp = /^[A-Z][A-Za-z ]*(?: & [A-Z][a-z]+)?: /.test(en);
      const kp = /^[^\s“"]+(?: Joe|과 Sara)?: /.test(ko[j]);
      if (sp !== kp) throw new Error(`${L} Ch${ch.no} #${j + 1}: 화자 표시 불일치\n  ${en}\n  ${ko[j]}`);
    });
    const out = path.join(__dirname, 'data', L, `${ch.no}.json`);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, JSON.stringify({
      exam: '신서중 1학년 · 미래엔(문영인)', question_no: String(ch.no), subtitle: ch.subtitle,
      passage: ch.sentences, passage_ko: ko,
    }, null, 2) + '\n', 'utf8');
  });
  console.log(`  ${L}: ${SOURCE.length}챕터 · ${SOURCE.reduce((a, c) => a + c.sentences.length, 0)}문장`);
}
